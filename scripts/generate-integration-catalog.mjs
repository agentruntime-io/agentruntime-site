/**
 * Build tool groups for curated integration pages from connectors/catalog/{slug}.json.
 * Slugs are taken from src/content/integrations/*.json.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SITE_ROOT = join(__dirname, "..");
const REPO_ROOT = join(SITE_ROOT, "..");
const CONTENT_DIR = join(SITE_ROOT, "src", "content", "integrations");
const CATALOG_DIR = join(REPO_ROOT, "connectors", "catalog");
const OUT_FILE = join(SITE_ROOT, "src", "lib", "integrationCatalog.generated.ts");

function titleCase(value) {
  return value
    .split(/[\s_-]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function inferGroup(toolName, prefix) {
  const rest = toolName.startsWith(prefix)
    ? toolName.slice(prefix.length)
    : toolName;
  const lower = rest.toLowerCase();
  if (lower.includes("draft")) return "Drafts";
  if (lower.includes("thread")) return "Threads";
  if (lower.includes("attachment")) return "Attachments";
  if (lower.includes("label")) return "Labels";
  if (lower.includes("profile")) return "Profile";
  if (lower.includes("channel")) return "Channels";
  if (lower.includes("reaction")) return "Reactions";
  if (lower.includes("user")) return "Users";
  if (lower.includes("approval")) return "Governance";
  if (
    lower.includes("send") ||
    lower.includes("reply") ||
    lower.includes("post")
  ) {
    return "Send";
  }
  if (
    lower.includes("search") ||
    lower.includes("list") ||
    lower.includes("get") ||
    lower.includes("read")
  ) {
    return "Read";
  }
  return "Actions";
}

function inferAccess(toolName) {
  const lower = toolName.toLowerCase();
  if (
    lower.includes("send") ||
    lower.includes("create") ||
    lower.includes("reply") ||
    lower.includes("post") ||
    lower.includes("add") ||
    lower.includes("delete") ||
    lower.includes("update")
  ) {
    return "Write";
  }
  return "Read";
}

function humanLabel(toolName, prefix, description) {
  const rest = toolName.startsWith(prefix)
    ? toolName.slice(prefix.length)
    : toolName;
  const words = rest.split("_").filter(Boolean);
  if (words.length === 0) {
    return description?.split(".")[0] || toolName;
  }
  return titleCase(words.join(" "));
}

function buildCatalogEntry(slug) {
  const catalogPath = join(CATALOG_DIR, `${slug}.json`);
  if (!existsSync(catalogPath)) {
    console.warn(`generate-integration-catalog: missing catalog for ${slug}`);
    return null;
  }

  const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
  const prefix =
    catalog.config?.prefix ||
    `${catalog.adapter || slug}_` ||
    `${slug}_`;

  const groups = new Map();
  for (const tool of catalog.tools || []) {
    const group = inferGroup(tool.name, prefix);
    const access = inferAccess(tool.name);
    const entry = {
      name: tool.name,
      label: humanLabel(tool.name, prefix, tool.description),
      description: tool.description || "",
      group,
      access,
    };
    if (!groups.has(group)) {
      groups.set(group, []);
    }
    groups.get(group).push(entry);
  }

  const toolGroups = [...groups.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, tools]) => ({
      name,
      tools: tools.sort((a, b) => a.label.localeCompare(b.label)),
    }));

  return {
    slug,
    adapter: catalog.adapter || slug,
    toolCount: catalog.tools?.length || 0,
    toolGroups,
  };
}

const slugs = readdirSync(CONTENT_DIR)
  .filter((name) => name.endsWith(".json"))
  .map((name) => name.replace(/\.json$/, ""))
  .sort();

const entries = slugs
  .map((slug) => buildCatalogEntry(slug))
  .filter(Boolean);

const source = `/* eslint-disable */
// Generated by scripts/generate-integration-catalog.mjs — do not edit.
export type GeneratedIntegrationTool = {
  name: string;
  label: string;
  description: string;
  group: string;
  access: "Read" | "Write";
};

export type GeneratedIntegrationToolGroup = {
  name: string;
  tools: readonly GeneratedIntegrationTool[];
};

export type GeneratedIntegrationCatalogEntry = {
  slug: string;
  adapter: string;
  toolCount: number;
  toolGroups: readonly GeneratedIntegrationToolGroup[];
};

export const integrationCatalogBySlug = ${JSON.stringify(
  Object.fromEntries(entries.map((entry) => [entry.slug, entry])),
  null,
  2,
)} satisfies Record<string, GeneratedIntegrationCatalogEntry>;

export const curatedIntegrationSlugs = ${JSON.stringify(slugs)} as const;
`;

writeFileSync(OUT_FILE, source);
console.log(
  `generate-integration-catalog: wrote ${entries.length} entries to ${OUT_FILE}`,
);
